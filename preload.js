// Puente entre la interfaz y el proceso principal.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('sq', {
  loadState: () => ipcRenderer.sendSync('state:load'),
  saveState: s => ipcRenderer.send('state:save', s),
  saveStateSync: s => ipcRenderer.sendSync('state:save', s),
  ready: () => ipcRenderer.send('ready'),
  setMode: (m, w, h, first) => ipcRenderer.send('win:mode', m, w, h, !!first),
  ignoreMouse: on => ipcRenderer.send('win:ignore', on),
  drag: on => ipcRenderer.send('win:drag', on),
  hide: () => ipcRenderer.send('win:hide'),
  winPrefs: p => ipcRenderer.send('win:prefs', p),
  openDialog: formats => ipcRenderer.invoke('dlg:open', formats),
  expand: (paths, formats) => ipcRenderer.invoke('files:expand', paths, formats),
  pathFor: f => webUtils.getPathForFile(f),
  readTags: (file, cover) => ipcRenderer.invoke('tags:read', file, cover),
  writeTags: (file, t, cover, dest) => ipcRenderer.invoke('tags:write', file, t, cover, dest),
  saveDialog: (name, ext) => ipcRenderer.invoke('dlg:save', name, ext),
  saveList: items => ipcRenderer.invoke('list:save', items),
  mbSearch: q => ipcRenderer.invoke('mb:search', q),
  mbCover: id => ipcRenderer.invoke('mb:cover', id),
  sysVolume: v => ipcRenderer.send('sys:volume', v),
  getSysVolume: () => ipcRenderer.invoke('sys:getVolume'),
  recStart: sr => ipcRenderer.invoke('rec:start', sr),
  recChunk: buf => ipcRenderer.send('rec:chunk', buf),
  recStop: () => ipcRenderer.send('rec:stop'),
  openExternal: url => ipcRenderer.send('open:external', url),
  openMusic: () => ipcRenderer.send('open:music'),
  version: ipcRenderer.sendSync('app:version'),
  resetAll: () => ipcRenderer.send('app:reset'),
  help: () => ipcRenderer.send('help'),
  on: (ch, fn) => ipcRenderer.on('sq:' + ch, (e, ...a) => fn(...a)),
});
